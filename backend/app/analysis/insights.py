"""Deterministic, source-grounded insights.

Every insight here is arithmetic over facts the document itself published, and
every one carries the fact ids it was computed from.  Nothing is generated by a
language model, nothing is interpreted, and nothing is asserted that the
supporting facts do not contain.

The distinction that matters: an insight *states a computed relationship*
("EBITDA margin moved from 15.2% to 16.4%, +120 bps"), it does not *explain*
one ("driven by better refining spreads").  Explanations are only ever quoted
from management commentary, never authored.
"""
from __future__ import annotations

from collections import defaultdict

from app.core.ids import stable_id
from app.core.logging import get_logger
from app.extraction import taxonomy
from app.models.enums import (
    DerivationStatus, InsightType, ValueType,
)
from app.models.schemas import DerivedMetric, FinancialFact, Insight

log = get_logger("analysis.insights")

# A movement smaller than this is noise, not an insight.
MIN_GROWTH_PCT = 2.0
MIN_MARGIN_BPS = 25.0


def _fmt(value: float | None, value_type: ValueType, currency: str = "",
         unit: str = "") -> str:
    if value is None:
        return "n/a"
    if value_type == ValueType.PERCENTAGE:
        return f"{value:,.2f}%"
    if value_type == ValueType.RATIO:
        return f"{value:,.2f}x"
    prefix = f"{currency} " if currency and currency != "UNKNOWN" else ""
    suffix = f" {unit}" if unit and unit != "none" else ""
    return f"{prefix}{value:,.2f}{suffix}"


def _period_rank(fact: FinancialFact) -> tuple[str, int, int]:
    """Where a figure sits in time, for ordering a series.

    The end date leads, because it is the only key that orders every kind of
    period against every other: a quarter, a half year and a balance-sheet
    instant all have one, and only some of them have a fiscal year and a
    quarter number.

    Ranking on fiscal year and quarter alone made every "As at" date equal.
    Four readings of one balance -- December 2018, June 2025, March 2026 --
    then sorted in whatever order they were extracted, and the series reported
    that total assets had "declined 58.7 % in As at 2018-12-31" by comparing
    2018 against 2025 and calling the earlier figure the later one.
    """
    p = fact.period_normalized
    if p is None:
        return ("", 0, 0)
    return (str(p.end_date or ""), (p.fiscal_year or 0), (p.quarter or 0))


def _orderable(a: FinancialFact, b: FinancialFact) -> bool:
    """Whether these two figures can be placed in time relative to each other.

    Where they cannot, no growth is reported. A change between two figures
    whose order is unknown is not a change in either direction.
    """
    return _period_rank(a) != _period_rank(b)


def _series(facts: list[FinancialFact]) -> dict[tuple, list[FinancialFact]]:
    out: dict[tuple, list[FinancialFact]] = defaultdict(list)
    for f in facts:
        if f.canonical_metric and f.period and f.value is not None:
            out[(f.entity_id or f.entity or "", f.canonical_metric)].append(f)
    for members in out.values():
        members.sort(key=_period_rank, reverse=True)
    return out


def _growth_insights(document_id: str, facts: list[FinancialFact]) -> list[Insight]:
    out: list[Insight] = []
    for (entity, metric), members in _series(facts).items():
        if len(members) < 2:
            continue
        definition = taxonomy.get(metric)
        if definition is None or definition.is_rate:
            continue
        current, prior = members[0], members[1]
        if current.period == prior.period or prior.value in (None, 0):
            continue
        if not _orderable(current, prior):
            continue
        if current.currency != prior.currency or current.unit != prior.unit:
            continue                      # never compare unreconciled scales
        change = (current.value - prior.value) / abs(prior.value) * 100.0
        if abs(change) < MIN_GROWTH_PCT:
            continue
        direction = "rose" if change > 0 else "declined"
        reported = (" The document states this change directly."
                    if current.growth_reported else
                    " Computed by FinSight from the two reported figures.")
        out.append(Insight(
            id=stable_id("insight", document_id, entity, metric, "growth",
                         current.period or ""),
            document_id=document_id, insight_type=InsightType.GROWTH,
            headline=(f"{definition.display} {direction} "
                      f"{abs(change):,.1f}% to "
                      f"{_fmt(current.value, current.value_type, str(current.currency), str(current.unit))} "
                      f"in {current.period}"),
            detail=(f"{current.period}: "
                    f"{_fmt(current.value, current.value_type, str(current.currency), str(current.unit))} "
                    f"vs {prior.period}: "
                    f"{_fmt(prior.value, prior.value_type, str(prior.currency), str(prior.unit))}."
                    + reported),
            entity_id=current.entity_id, entity_name=current.entity,
            metric=metric, periods=[current.period or "", prior.period or ""],
            supporting_fact_ids=[current.fact_id, prior.fact_id],
            value=current.value, comparison_value=prior.value,
            change=round(change, 2), change_unit="percent",
            derivation=(DerivationStatus.REPORTED if current.growth_reported
                        else DerivationStatus.CALCULATED),
            confidence=round(min(current.confidence, prior.confidence), 3),
            source_pages=sorted({p for p in (current.source_page,
                                             prior.source_page) if p}),
        ))
    return out


def _margin_insights(document_id: str, facts: list[FinancialFact],
                     derived: list[DerivedMetric]) -> list[Insight]:
    """Margin movements in basis points.

    Series are keyed by derivation as well as by entity and metric: a margin the
    document printed and one FinSight computed are NOT two points on the same
    series.  Comparing them would report an arithmetic difference as if it were
    a business movement -- exactly the kind of unsupported conclusion this
    system must never draw.  When the two disagree, that is an anomaly, not an
    insight, and the anomaly detector reports it as one.
    """
    points: dict[tuple, dict[str, tuple[float, list[str], tuple[int, int]]]] = (
        defaultdict(dict))
    ranks = {f.period: _period_rank(f) for f in facts if f.period}

    for f in facts:
        definition = taxonomy.get(f.canonical_metric or "")
        if (definition is None or f.value is None or not f.period
                or f.value_type != ValueType.PERCENTAGE
                or definition.category != "margins"):
            continue
        key = (f.entity_id or f.entity or "", f.canonical_metric,
               str(DerivationStatus.REPORTED))
        points[key][f.period] = (f.value, [f.fact_id], _period_rank(f))

    for m in derived:
        if m.value is None or not m.period or m.value_type != ValueType.PERCENTAGE:
            continue
        key = (m.entity_id or m.entity_name or "", m.canonical_metric,
               str(DerivationStatus.CALCULATED))
        points[key][m.period] = (m.value, list(m.input_fact_ids),
                                 ranks.get(m.period, (0, 0)))

    out: list[Insight] = []
    for (entity, metric, kind), by_period in points.items():
        if len(by_period) < 2:
            continue
        # order by resolved period, never by label text: "Q4 FY25" sorts above
        # "Q1 FY26" alphabetically but is the earlier quarter
        ordered = sorted(by_period.items(), key=lambda kv: kv[1][2], reverse=True)
        cur_period, (cur_value, cur_ids, _) = ordered[0]
        pri_period, (pri_value, pri_ids, _) = ordered[1]
        bps = (cur_value - pri_value) * 100.0
        if abs(bps) < MIN_MARGIN_BPS:
            continue
        derivation = DerivationStatus(kind)
        definition = taxonomy.get(metric)
        display = definition.display if definition else metric
        direction = "expanded" if bps > 0 else "contracted"
        basis = (" Both rates were reported by the document."
                 if derivation == DerivationStatus.REPORTED else
                 " Both rates were computed by FinSight from figures the "
                 "document reported; reported and calculated rates are never "
                 "compared against one another.")
        out.append(Insight(
            id=stable_id("insight", document_id, entity, metric, "margin",
                         str(derivation), cur_period),
            document_id=document_id, insight_type=InsightType.MARGIN_MOVEMENT,
            headline=(f"{display} {direction} {abs(bps):,.0f} bps to "
                      f"{cur_value:,.2f}% in {cur_period}"),
            detail=(f"{cur_period}: {cur_value:,.2f}% vs {pri_period}: "
                    f"{pri_value:,.2f}%." + basis),
            entity_id=None, entity_name=entity or None, metric=metric,
            periods=[cur_period, pri_period],
            supporting_fact_ids=[*cur_ids, *pri_ids],
            value=cur_value, comparison_value=pri_value,
            change=round(bps, 1), change_unit="bps",
            derivation=derivation, confidence=0.8,
        ))
    return out


def _segment_insights(document_id: str, facts: list[FinancialFact]) -> list[Insight]:
    """Which reporting unit contributed most, and which outgrew the group.

    Contribution is only computed when a group-level total for the *same*
    metric, period, unit and currency exists.  Segment figures are never summed
    into a total the document did not print.
    """
    out: list[Insight] = []
    by_key: dict[tuple, list[FinancialFact]] = defaultdict(list)
    for f in facts:
        if f.canonical_metric and f.period and f.value is not None:
            by_key[(f.canonical_metric, f.period)].append(f)

    for (metric, period), members in by_key.items():
        definition = taxonomy.get(metric)
        if definition is None or definition.is_rate:
            continue
        parents = [f for f in members if not f.parent_entity_id]
        children = [f for f in members if f.parent_entity_id]
        if not parents or not children:
            continue
        total = max(parents, key=lambda f: abs(f.value or 0))
        if not total.value:
            continue
        comparable = [c for c in children
                      if c.currency == total.currency and c.unit == total.unit
                      and c.parent_entity_id == total.entity_id]
        if not comparable:
            continue
        largest = max(comparable, key=lambda f: abs(f.value or 0))
        share = largest.value / total.value * 100.0
        if not 0 < share <= 100.0:
            continue                      # an impossible share is not an insight
        out.append(Insight(
            id=stable_id("insight", document_id, metric, period, "segment"),
            document_id=document_id,
            insight_type=InsightType.SEGMENT_CONTRIBUTION,
            headline=(f"{largest.entity} contributed {share:,.1f}% of "
                      f"{definition.display} in {period}"),
            detail=(f"{largest.entity}: "
                    f"{_fmt(largest.value, largest.value_type, str(largest.currency), str(largest.unit))} "
                    f"of {total.entity}'s "
                    f"{_fmt(total.value, total.value_type, str(total.currency), str(total.unit))}. "
                    f"Share computed from two figures the document reported; "
                    f"segment values were not summed to produce the total."),
            entity_id=largest.entity_id, entity_name=largest.entity,
            metric=metric, periods=[period],
            supporting_fact_ids=[largest.fact_id, total.fact_id],
            value=largest.value, comparison_value=total.value,
            change=round(share, 2), change_unit="percent_of_total",
            derivation=DerivationStatus.CALCULATED,
            confidence=round(min(largest.confidence, total.confidence) * 0.95, 3),
            source_pages=sorted({p for p in (largest.source_page,
                                             total.source_page) if p}),
        ))
    return out


def _leverage_insights(document_id: str, derived: list[DerivedMetric],
                       ) -> list[Insight]:
    out: list[Insight] = []
    by_key: dict[tuple, list[DerivedMetric]] = defaultdict(list)
    for m in derived:
        if m.canonical_metric in ("net_debt_to_ebitda", "debt_to_equity",
                                  "interest_coverage") and m.value is not None:
            by_key[(m.entity_id or m.entity_name or "",
                    m.canonical_metric)].append(m)

    for (entity, metric), members in by_key.items():
        if len(members) < 2:
            continue
        members.sort(key=lambda m: m.period or "", reverse=True)
        current, prior = members[0], members[1]
        if prior.value in (None, 0):
            continue
        change = current.value - prior.value
        if abs(change) < 0.05:
            continue
        out.append(Insight(
            id=stable_id("insight", document_id, entity, metric, "leverage"),
            document_id=document_id, insight_type=InsightType.LEVERAGE_CHANGE,
            headline=(f"{current.metric_display} moved from {prior.value:,.2f}x "
                      f"to {current.value:,.2f}x"),
            detail=(f"Computed as {current.formula}. Both points are FinSight "
                    f"calculations from reported balance-sheet figures, not "
                    f"ratios the document published."),
            entity_id=current.entity_id, entity_name=current.entity_name,
            metric=metric, periods=[current.period or "", prior.period or ""],
            supporting_fact_ids=[*current.input_fact_ids, *prior.input_fact_ids],
            value=current.value, comparison_value=prior.value,
            change=round(change, 3), change_unit="x",
            derivation=DerivationStatus.CALCULATED,
            confidence=round(min(current.confidence, prior.confidence), 3),
            source_pages=sorted(set(current.source_pages
                                    + prior.source_pages)),
        ))
    return out


def generate_insights(document_id: str, facts: list[FinancialFact],
                      derived: list[DerivedMetric] | None = None,
                      *, limit: int = 40) -> list[Insight]:
    """Produce every insight the facts support, most significant first."""
    derived = derived or []
    out: list[Insight] = []
    out.extend(_growth_insights(document_id, facts))
    out.extend(_margin_insights(document_id, facts, derived))
    out.extend(_segment_insights(document_id, facts))
    out.extend(_leverage_insights(document_id, derived))

    def magnitude(i: Insight) -> float:
        scale = {"bps": 0.01, "percent": 1.0, "percent_of_total": 0.5,
                 "x": 10.0}.get(i.change_unit or "", 1.0)
        return abs(i.change or 0) * scale * max(i.confidence, 0.1)

    out.sort(key=magnitude, reverse=True)
    log.info("insights.generated", document_id=document_id, count=len(out))
    return out[:limit]
